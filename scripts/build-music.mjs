import { readFile, writeFile, mkdir, readdir, unlink } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'features/music'), output = path.join(root, 'public/xp/music');
const hash = text => createHash('sha256').update(text).digest('hex').slice(0, 12);
const core = await readFile(path.join(source, 'core.mjs'), 'utf8');
const css = await readFile(path.join(source, 'style.css'), 'utf8');
const coreName = `core-${hash(core)}.mjs`, cssName = `style-${hash(css)}.css`;
const app = (await readFile(path.join(source, 'app.js'), 'utf8')).replace("'./core.mjs'", `'./${coreName}'`).replace("'./style.css?v='", `'./${cssName}?v='`);
const appName = `app-${hash(app)}.js`;
await mkdir(output, { recursive: true });
for (const file of await readdir(output)) if (/^(?:app|core|style)-[a-f0-9]+\.(?:js|mjs|css)$/.test(file) && ![coreName, cssName, appName].includes(file)) await unlink(path.join(output, file));
await writeFile(path.join(output, coreName), core); await writeFile(path.join(output, cssName), css); await writeFile(path.join(output, appName), app);
const indexPath = path.join(root, 'public/xp/index.html');
let html = await readFile(indexPath, 'utf8');
html = html.replace(/\s*<script[^>]+data-xp-music[^>]*><\/script>/g, '');
html = html.replace('</body>', `<script type="module" data-xp-music src="./music/${appName}"></script>\n</body>`);
await writeFile(indexPath, html);
const manifestPath = path.join(root, 'public/xp/offline-manifest.json'), manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
manifest.files = [...manifest.files.filter(x => !x.startsWith('music/')), ...[coreName, cssName, appName].map(x => 'music/' + x)];
await writeFile(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
await writeFile(path.join(output, 'version.json'), JSON.stringify({ version: '20261023-2', app: appName, core: coreName, css: cssName }) + '\n');
console.log(`Music built: ${appName}; ${coreName}; ${cssName}`);
